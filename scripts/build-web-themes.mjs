#!/usr/bin/env node
// Builds the opencode-compatible theme engine for the Aurora web panel.
//
//   node scripts/build-web-themes.mjs
//
// Inputs  (vendored from github.com/anomalyco/opencode, MIT):
//   scripts/opencode-theme-src/*.ts        — color math + v2 token resolver
//   scripts/opencode-theme-src/themes/*.json — theme definitions
// Outputs (committed, served by internal/web):
//   internal/web/dist/theme/*.js           — ES modules for the browser
//   internal/web/dist/theme.css            — static tokens for the default theme
//
// The panel never fetches anything at runtime: themes are local files.

import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, copyFileSync } from "node:fs"
import { stripTypeScriptTypes } from "node:module"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, "..")
const src = join(root, "scripts/opencode-theme-src")
const outDir = join(root, "internal/web/dist/theme")
const outFile = (name) => join(outDir, name)

const TS_MODULES = [
  "color.ts",
  "v2/avatar.ts",
  "v2/default-primitives.ts",
  "v2/mapping.ts",
  "v2/foreground.ts",
  "v2/resolve.ts",
]

// "./types" / "../color" -> "./color.js" (everything is flattened into dist/theme).
function rewriteImports(code) {
  return code.replace(/from\s+["'](\.{1,2}\/)([A-Za-z0-9_-]+)["']/g, 'from "./$2.js"')
}

rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })

for (const file of TS_MODULES) {
  const raw = readFileSync(join(src, file), "utf8")
  const js = rewriteImports(stripTypeScriptTypes(raw, { mode: "strip" }))
  writeFileSync(outFile(file.split("/").pop().replace(/\.ts$/, ".js")), js)
}

const names = readdirSync(join(src, "themes"))
  .filter((f) => f.endsWith(".json"))
  .sort()

const themes = names.map((file) => {
  const raw = JSON.parse(readFileSync(join(src, "themes", file), "utf8"))
  const variant = (v) => {
    const out = { palette: v.palette }
    if (v.overrides) out.overrides = v.overrides
    if (v.v2Overrides) out.v2Overrides = v.v2Overrides
    return out
  }
  return { id: raw.id, name: raw.name, light: variant(raw.light), dark: variant(raw.dark) }
})

writeFileSync(
  outFile("themes-data.js"),
  "// Generated by scripts/build-web-themes.mjs — theme definitions from opencode (MIT).\n" +
    `export const THEMES = ${JSON.stringify(themes)}\n`,
)

// The runtime engine is plain JS with ESM imports into the generated modules.
copyFileSync(join(root, "scripts/theme-engine.js"), outFile("index.js"))

const ids = themes.map((t) => t.id)
if (!ids.includes("oc-2")) {
  throw new Error("default theme oc-2 is missing")
}

// Static fallback tokens for the default theme (OC-2). Mirrors what the runtime
// engine injects, so the first paint already matches the chosen colour scheme.
const { resolveThemeVariantV2 } = await import(outFile("resolve.js"))
const { THEMES } = await import(outFile("themes-data.js"))
const oc2 = THEMES.find((t) => t.id === "oc-2")

const colorsCss = readFileSync(join(src, "colors.css"), "utf8")
const alpha = [...colorsCss.matchAll(/(--v2-alpha-(?:dark|light)-\d+:\s*[^;]+;)/g)]
  .map((m) => `  ${m[1]}`)
  .join("\n")

function tokensCss(tokens) {
  return Object.entries(tokens)
    .map(([key, value]) => `  --${key}: ${value};`)
    .join("\n")
}

const themeCss = `/* Generated by scripts/build-web-themes.mjs — opencode default theme (OC-2), MIT. */
/* Alpha ramps are static; hue ramps and semantics are resolved from the theme. */
:root {
  color-scheme: light;

${alpha}

${tokensCss(resolveThemeVariantV2(oc2.light, false))}
}

[data-color-scheme="dark"] {
  color-scheme: dark;

${tokensCss(resolveThemeVariantV2(oc2.dark, true))}
}
`

writeFileSync(join(root, "internal/web/dist/theme.css"), themeCss)

console.log(
  `theme engine: ${TS_MODULES.length} modules, ${themes.length} themes -> internal/web/dist/theme/`,
)
console.log("static tokens: internal/web/dist/theme.css")
